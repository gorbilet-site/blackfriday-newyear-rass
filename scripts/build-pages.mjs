import { execFileSync } from "node:child_process";
import { cpSync, existsSync, lstatSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve, relative } from "node:path";
const root = resolve(import.meta.dirname, "..");
const url = "https://gorbilet-site.github.io/blackfriday-newyear-rass";
const env = { ...process.env, STATIC_EXPORT: "1", NEXT_PUBLIC_BASE_PATH: "/blackfriday-newyear-rass", NEXT_PUBLIC_SITE_URL: url };
execFileSync(process.execPath, [resolve(root, "node_modules/next/dist/bin/next"), "build", "--webpack"], {cwd:root,env,stdio:"inherit"});
const out = resolve(root,"out");
const allFiles = (dir) => readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?allFiles(resolve(dir,e.name)):[resolve(dir,e.name)]);
const pages = allFiles(out).filter(f=>f.endsWith("index.html")&&!/[\\/](?:404|_not-found)[\\/]/.test(f));
const locations = pages.map(f=>relative(out,f).replaceAll("\\","/").replace(/index\.html$/,""));
writeFileSync(resolve(out,"sitemap.xml"), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+locations.map(p=>`<url><loc>${url}/${p}</loc></url>`).join("\n")+'\n</urlset>\n');
writeFileSync(resolve(out,"robots.txt"), `User-agent: *\nAllow: /\nSitemap: ${url}/sitemap.xml\n`);
const docs=resolve(root,"docs");
if(relative(root,docs)!=="docs"||(existsSync(docs)&&lstatSync(docs).isSymbolicLink()))throw new Error("Unsafe Pages output path");
rmSync(docs,{recursive:true,force:true});
mkdirSync(docs,{recursive:true});
cpSync(out,docs,{recursive:true});
writeFileSync(resolve(docs,".nojekyll"),"");
console.log("GitHub Pages output: docs/");
